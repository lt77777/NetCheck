/**
 * State wage income tax parameters for tax year 2026.
 *
 * Rates, brackets, standard deductions, and personal exemptions:
 * Tax Foundation, "2026 State Income Tax Rates and Brackets"
 * (compiled from state statutes, forms, and instructions; as of 11 Feb 2026).
 *
 * California standard deduction for 2026 estimated tax: FTB Form 540-ES
 * instructions ($5,706 single / $11,412 joint). CA FTB had not published a
 * separate 2026 inflation-adjusted rate schedule at the time of this build;
 * brackets below are the Tax Foundation 2026 table (2025 inflation-adjusted
 * widths — see footnote (j) on that page).
 *
 * Washington taxes certain capital gains only — treated as $0 for wages.
 */

function bracketsFromThresholds(rows) {
  const out = [];
  for (let i = 0; i < rows.length; i += 1) {
    const next = rows[i + 1];
    out.push({
      max: next ? next.min : Infinity,
      rate: rows[i].rate,
    });
  }
  return out;
}

function state(cfg) {
  const singleT = cfg.single || [];
  const jointT = cfg.marriedJoint || cfg.single || [];
  return {
    code: cfg.code,
    name: cfg.name,
    slug: cfg.slug,
    hasIncomeTax: cfg.hasIncomeTax !== false,
    pretaxReducesState: cfg.pretaxReducesState !== false,
    usesFederalStandardDeduction: Boolean(cfg.usesFederalStandardDeduction),
    standardDeduction: cfg.standardDeduction || { single: 0, marriedJoint: 0 },
    personalExemption: cfg.personalExemption || { single: 0, marriedJoint: 0 },
    exemptionCredit: cfg.exemptionCredit || { single: 0, marriedJoint: 0 },
    brackets: {
      single: cfg.hasIncomeTax === false ? [] : bracketsFromThresholds(singleT),
      marriedJoint: cfg.hasIncomeTax === false ? [] : bracketsFromThresholds(jointT),
    },
    exemptionByAgi: cfg.exemptionByAgi || null,
    notes: cfg.notes || "",
  };
}

function none(code, name, slug, notes) {
  return state({
    code,
    name,
    slug,
    hasIncomeTax: false,
    notes: notes || "No state individual income tax on wages.",
  });
}

